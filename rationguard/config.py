"""Configuration: everything secret comes from the environment (.env), never
from the source code and never from the database.

Fail closed: if a key is missing or still a placeholder, the app refuses to
start. A system that silently runs with a weak default key is worse than one
that does not run.
"""
from __future__ import annotations

import base64
import os
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from dotenv import load_dotenv

PROJECT_ROOT = Path(__file__).resolve().parent.parent


class ConfigError(RuntimeError):
    """Raised when configuration is missing or unsafe."""


def _hex_key(name: str) -> bytes:
    value = os.environ.get(name, "")
    try:
        key = bytes.fromhex(value)
    except ValueError:
        key = b""
    if len(key) < 32:
        raise ConfigError(
            f"{name} is missing or not a 32-byte hex key. "
            "Run `python scripts/setup_keys.py` to generate fresh keys."
        )
    return key


def _text(name: str, default: str | None = None) -> str:
    value = os.environ.get(name, default)
    if not value or value.startswith("REPLACE_ME"):
        raise ConfigError(f"{name} is not set. Run `python scripts/setup_keys.py`.")
    return value


def _path(name: str, default: str) -> Path:
    path = Path(os.environ.get(name, default))
    return path if path.is_absolute() else PROJECT_ROOT / path


@dataclass(frozen=True)
class Settings:
    tx_hmac_key: bytes        # signs transactions
    audit_hmac_key: bytes     # signs audit log entries
    record_hmac_key: bytes    # signs household / user / change-request rows
    fernet_key: bytes         # encrypts personal fields
    session_secret: bytes     # derives CSRF tokens
    db_path: Path
    anchor_file: Path
    # Optional remote database (Turso). Empty = use the local SQLite file.
    database_url: str
    database_auth_token: str
    # Where signed anchors are kept: "file" (default) or "db" (hosted demo).
    anchor_store: str
    signing_private_key: Path
    signing_public_key: Path
    anchor_every: int
    cookie_secure: bool
    business_start_hour: int
    business_end_hour: int
    tz_offset_minutes: int


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    # override=False: real environment variables win over the .env file.
    load_dotenv(PROJECT_ROOT / ".env", override=False)
    return Settings(
        tx_hmac_key=_hex_key("RG_TX_HMAC_KEY"),
        audit_hmac_key=_hex_key("RG_AUDIT_HMAC_KEY"),
        record_hmac_key=_hex_key("RG_RECORD_HMAC_KEY"),
        fernet_key=_text("RG_FERNET_KEY").encode(),
        session_secret=_hex_key("RG_SESSION_SECRET"),
        db_path=_path("RG_DB_PATH", "rationguard.db"),
        anchor_file=_path("RG_ANCHOR_FILE", "anchors/anchors.jsonl"),
        database_url=os.environ.get("RG_DATABASE_URL", "").strip(),
        database_auth_token=os.environ.get("RG_DATABASE_AUTH_TOKEN", "").strip(),
        anchor_store=os.environ.get("RG_ANCHOR_STORE", "file").strip().lower(),
        signing_private_key=_path("RG_SIGNING_PRIVATE_KEY", "keys/anchor_ed25519_private.pem"),
        signing_public_key=_path("RG_SIGNING_PUBLIC_KEY", "keys/anchor_ed25519_public.pem"),
        anchor_every=max(1, int(os.environ.get("RG_ANCHOR_EVERY", "5"))),
        cookie_secure=os.environ.get("RG_COOKIE_SECURE", "false").lower() == "true",
        business_start_hour=int(os.environ.get("RG_BUSINESS_START_HOUR", "6")),
        business_end_hour=int(os.environ.get("RG_BUSINESS_END_HOUR", "22")),
        tz_offset_minutes=int(os.environ.get("RG_TZ_OFFSET_MINUTES", "330")),
    )


def signing_key_pem(which: str) -> bytes:
    """Return the Ed25519 key ('private' or 'public') as PEM bytes.

    Normally it is read from the file in keys/. Serverless hosts have no place
    to keep a private file, so there the PEM is supplied base64-encoded in an
    environment variable (the host's encrypted secret store) instead.
    """
    encoded = os.environ.get(f"RG_SIGNING_{which.upper()}_KEY_B64", "")
    if encoded:
        return base64.b64decode(encoded)
    settings = get_settings()
    path = settings.signing_private_key if which == "private" else settings.signing_public_key
    if not path.exists():
        raise ConfigError(f"Signing key {path} not found. Run `python scripts/setup_keys.py`.")
    return path.read_bytes()


def seed_password() -> str:
    """Password for the fictional demo users. Generated by the setup script."""
    load_dotenv(PROJECT_ROOT / ".env", override=False)
    return _text("RG_SEED_PASSWORD")
